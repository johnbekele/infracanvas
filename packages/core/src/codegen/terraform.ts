function generateModuleVariables(serviceId: string): string {
  const service = getServiceById(serviceId);
  if (!service) return '# No variables defined\n';

  let content = `# Variables for ${service.name} module\n\n`;
  content += `variable "name" {\n  type = string\n}\n\n`;
  content += `variable "environment" {\n  type = string\n}\n\n`;

  service.properties.forEach((prop) => {
    const tfType =
      prop.type === 'boolean' ? 'bool' : prop.type === 'number' ? 'number' : 'string';
    content += `variable "${prop.name}" {\n`;
    content += `  type    = ${tfType}\n`;
    content += `  default = ${JSON.stringify(prop.default)}\n`;
    content += `}\n\n`;
  });

  return content;
}

function generateModuleOutputs(serviceId: string): string {
  return `# Outputs for ${serviceId} module

output "id" {
  description = "Resource ID"
  value       = aws_${serviceId === 'api-gateway' ? 'apigatewayv2_api' : serviceId.replace('-', '_')}.this.id
}
`;
}

function generateReadme(nodes: Node<ServiceNodeData>[]): string {
  const serviceTypes = [...new Set(nodes.map((n) => n.data.serviceId))];

  return `# Infrastructure as Code

Generated by [InfraCanvas](https://github.com/johnbekele/infracanvas)

## Resources

This project includes the following AWS resources:

${serviceTypes.map((s) => `- ${s}`).join('\n')}

## Usage

1. Configure AWS credentials
2. Run \`terraform init\`
3. Run \`terraform plan\`
4. Run \`terraform apply\`

## Customization

Each service is defined as a module in the \`modules/\` directory.
Modify the module inputs in \`main.tf\` or update the module definitions.
`;
}
