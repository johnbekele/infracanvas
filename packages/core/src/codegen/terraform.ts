function generateOutputsTf(nodes: Node<ServiceNodeData>[]): string {
  let content = `# Generated by InfraCanvas\n# Outputs\n\n`;
  const names = moduleNames(nodes);

  nodes.forEach((node) => {
    const name = names.get(node.id) as string;
    content += `output "${name}_id" {
  description = "ID of ${node.data.serviceName}"
  value       = module.${name}.id
}

`;
  });

  return content;
}

function generateServiceModule(
  serviceId: string,
  _nodes: Node<ServiceNodeData>[]
): TerraformFile[] {
  const main = generateModuleMain(serviceId);

  return [
    { path: `modules/${serviceId}/main.tf`, content: main },
    { path: `modules/${serviceId}/variables.tf`, content: generateModuleVariables(serviceId) },
    { path: `modules/${serviceId}/outputs.tf`, content: generateModuleOutputs(serviceId, main) },
  ];
}

function generateModuleMain(serviceId: string): string {
  const generators: Record<string, () => string> = {
    ec2: generateEC2Module,
    lambda: generateLambdaModule,
    s3: generateS3Module,
    rds: generateRDSModule,
    dynamodb: generateDynamoDBModule,
    'api-gateway': generateAPIGatewayModule,
    cloudfront: generateCloudFrontModule,
    sqs: generateSQSModule,
    sns: generateSNSModule,
    cognito: generateCognitoModule,
    vpc: generateVPCModule,
    ecs: generateECSModule,
    elasticache: generateElastiCacheModule,
    iam: generateIAMModule,
    route53: generateRoute53Module,
    'vpc-environment': generateVpcEnvironmentModule,
    'public-subnet': generateSubnetModule,
    'private-subnet': generateSubnetModule,
    alb: generateALBModule,
    nlb: generateNLBModule,
    'nat-gateway': generateNatGatewayModule,
  };

  const handWritten = generators[serviceId]?.();
  if (handWritten) return handWritten;

  // Anything without a hand-written module is emitted from its catalog entry.
  // The previous fallback was a comment, which meant a design containing a
  // service added after the generator was written exported code that silently
  // omitted it.
  const generic = emitTerraform(
    { id: serviceId, serviceId, properties: {}, name: 'this' },
    { tags: 'var.tags', parentFromVariables: true }
  );

  return (
    generic || `# ${serviceId} is a placement construct and generates no resource of its own\n`
  );
}

