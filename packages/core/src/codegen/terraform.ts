// Terraform Code Generator for InfraCanvas

import { getServiceById } from '../aws-services';
import type { ServiceNodeData } from '../types';

export interface TerraformFile {
  path: string;
  content: string;
}

export interface TerraformProject {
  files: TerraformFile[];
}

interface Node<T> {
  id: string;
  data: T;
  position: { x: number; y: number };
  parentNode?: string;
}

interface Edge {
  id: string;
  source: string;
  target: string;
}

function sanitizeName(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]/g, '_');
}

export function generateTerraformProject(
  nodes: Node<ServiceNodeData>[],
  _edges: Edge[]
): TerraformProject {
  const files: TerraformFile[] = [];

  if (nodes.length === 0) {
    files.push({
      path: 'main.tf',
      content: `# No resources to generate\n# Drag AWS services onto the canvas to create your architecture`,
    });
    return { files };
  }

  files.push({ path: 'main.tf', content: generateMainTf(nodes) });
  files.push({ path: 'variables.tf', content: generateVariablesTf() });
  files.push({ path: 'outputs.tf', content: generateOutputsTf(nodes) });

  const serviceTypes = new Set(nodes.map((n) => n.data.serviceId));
  serviceTypes.forEach((serviceId) => {
    const serviceNodes = nodes.filter((n) => n.data.serviceId === serviceId);
    const moduleFiles = generateServiceModule(serviceId, serviceNodes);
    files.push(...moduleFiles);
  });

  files.push({ path: 'README.md', content: generateReadme(nodes) });

  return { files };
}

export function generateTerraform(nodes: Node<ServiceNodeData>[], edges: Edge[]): string {
  const project = generateTerraformProject(nodes, edges);
  return project.files.map((f) => `# === ${f.path} ===\n${f.content}`).join('\n\n');
}

function generateMainTf(nodes: Node<ServiceNodeData>[]): string {
  const serviceTypes = new Set(nodes.map((n) => n.data.serviceId));

  let content = `# Generated by InfraCanvas
# Main Terraform Configuration

terraform {
  required_version = ">= 1.0"

  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }
  }
}

provider "aws" {
  region = var.aws_region

  default_tags {
    tags = {
      Environment = var.environment
      ManagedBy   = "Terraform"
      Project     = var.project_name
    }
  }
}

# Module Instances
`;

  serviceTypes.forEach((serviceId) => {
    const serviceNodes = nodes.filter((n) => n.data.serviceId === serviceId);
    serviceNodes.forEach((node) => {
      const resourceName = sanitizeName(node.data.serviceName);
      content += `
module "${resourceName}" {
  source = "./modules/${serviceId}"

  name        = "${resourceName}"
  environment = var.environment
${generateModuleInputs(node)}
}
`;
    });
  });

  return content;
}

function generateModuleInputs(node: Node<ServiceNodeData>): string {
  const props = node.data.properties;
  const lines: string[] = [];

  Object.entries(props).forEach(([key, value]) => {
    if (value !== '' && value !== undefined && value !== null) {
      if (typeof value === 'string') {
        lines.push(`  ${key} = "${value}"`);
      } else if (typeof value === 'boolean') {
        lines.push(`  ${key} = ${value}`);
      } else if (typeof value === 'number') {
        lines.push(`  ${key} = ${value}`);
      }
    }
  });

  return lines.join('\n');
}

function generateVariablesTf(): string {
  return `# Generated by InfraCanvas
# Input Variables

variable "aws_region" {
  description = "AWS region to deploy resources"
  type        = string
  default     = "us-east-1"
}

variable "environment" {
  description = "Environment name (e.g., dev, staging, prod)"
  type        = string
  default     = "production"
}

variable "project_name" {
  description = "Project name for tagging"
  type        = string
  default     = "infracanvas-project"
}
`;
}

function generateOutputsTf(nodes: Node<ServiceNodeData>[]): string {
  let content = `# Generated by InfraCanvas\n# Outputs\n\n`;

  nodes.forEach((node) => {
    const resourceName = sanitizeName(node.data.serviceName);
    content += `output "${resourceName}_id" {
  description = "ID of ${node.data.serviceName}"
  value       = module.${resourceName}.id
}

`;
  });

  return content;
}

function generateServiceModule(
  serviceId: string,
  _nodes: Node<ServiceNodeData>[]
): TerraformFile[] {
  const files: TerraformFile[] = [];

  files.push({
    path: `modules/${serviceId}/main.tf`,
    content: generateModuleMain(serviceId),
  });

  files.push({
    path: `modules/${serviceId}/variables.tf`,
    content: generateModuleVariables(serviceId),
  });

  files.push({
    path: `modules/${serviceId}/outputs.tf`,
    content: generateModuleOutputs(serviceId),
  });

  return files;
}

function generateModuleMain(serviceId: string): string {
  const generators: Record<string, () => string> = {
    ec2: generateEC2Module,
    lambda: generateLambdaModule,
    s3: generateS3Module,
    rds: generateRDSModule,
    dynamodb: generateDynamoDBModule,
    'api-gateway': generateAPIGatewayModule,
    cloudfront: generateCloudFrontModule,
    sqs: generateSQSModule,
    sns: generateSNSModule,
    cognito: generateCognitoModule,
    vpc: generateVPCModule,
    ecs: generateECSModule,
    elasticache: generateElastiCacheModule,
    iam: generateIAMModule,
    route53: generateRoute53Module,
    'vpc-environment': generateVpcEnvironmentModule,
    'public-subnet': generateSubnetModule,
    'private-subnet': generateSubnetModule,
    alb: generateALBModule,
    nlb: generateNLBModule,
    'nat-gateway': generateNatGatewayModule,
  };

  return generators[serviceId]?.() || `# TODO: Add ${serviceId} module configuration\n`;
}

