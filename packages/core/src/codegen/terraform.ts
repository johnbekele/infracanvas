function generateModuleVariables(serviceId: string): string {
  const service = getServiceById(serviceId);
  if (!service) return '# No variables defined\n';

  let content = `# Variables for ${service.name} module\n\n`;
  content += `variable "name" {\n  type = string\n}\n\n`;
  content += `variable "environment" {\n  type = string\n}\n\n`;
  content += `variable "tags" {\n  type    = map(string)\n  default = {}\n}\n\n`;

  // Declared even when the design leaves the node outside its container, so the
  // module stays valid either way and the omission surfaces as a null argument
  // rather than a parse error.
  parentLinks(serviceId).forEach((link) => {
    content += `variable "${snakeCase(link.argument)}" {\n`;
    content += `  description = "Identifier of the enclosing ${link.from}"\n`;
    content += `  type    = string\n`;
    content += `  default = null\n`;
    content += `}\n\n`;
  });

  service.properties.forEach((prop) => {
    const tfType = prop.type === 'boolean' ? 'bool' : prop.type === 'number' ? 'number' : 'string';
    content += `variable "${prop.name}" {\n`;
    content += `  type    = ${tfType}\n`;
    content += `  default = ${JSON.stringify(prop.default)}\n`;
    content += `}\n\n`;
  });

  return content;
}

/**
 * The module's own primary resource, read back out of the code it emitted.
 *
 * The output used to be guessed from the service id, which produced
 * `aws_public_subnet.this.id` and `aws_ecs.this.id` -- names that exist in no
 * provider. Reading the module means the export cannot disagree with what the
 * module declares, however that module was written.
 */
function primaryResource(moduleMain: string): string | null {
  return /resource "([a-z0-9_]+)" "this"/.exec(moduleMain)?.[1] ?? null;
}

function generateModuleOutputs(serviceId: string, moduleMain: string): string {
  const resource = primaryResource(moduleMain);

  if (!resource) {
    return `# Outputs for ${serviceId} module\n\n# ${serviceId} is a placement construct and has no resource to export\n`;
  }

  return `# Outputs for ${serviceId} module

output "id" {
  description = "Resource ID"
  value       = ${resource}.this.id
}
`;
}

function generateReadme(nodes: Node<ServiceNodeData>[]): string {
  const serviceTypes = [...new Set(nodes.map((n) => n.data.serviceId))];

  return `# Infrastructure as Code

Generated by [InfraCanvas](https://github.com/johnbekele/infracanvas)

## Resources

This project includes the following AWS resources:

${serviceTypes.map((s) => `- ${s}`).join('\n')}

## Usage

1. Configure AWS credentials
2. Run \`terraform init\`
3. Run \`terraform plan\`
4. Run \`terraform apply\`

## Customization

Each service is defined as a module in the \`modules/\` directory.
Modify the module inputs in \`main.tf\` or update the module definitions.
`;
}
