// Terraform Code Generator for InfraCanvas

import { getServiceById } from '../aws-services';
import { emitTerraform, snakeCase } from './emit';
import { containersFirst, parentLinks, placementOf } from './hierarchy';
import type { ServiceNodeData } from '../types';

export interface TerraformFile {
  path: string;
  content: string;
}

export interface TerraformProject {
  files: TerraformFile[];
}

interface Node<T> {
  id: string;
  data: T;
  position: { x: number; y: number };
  parentNode?: string;
}

interface Edge {
  id: string;
  source: string;
  target: string;
}

function sanitizeName(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]/g, '_');
}

/**
 * A distinct module label per node.
 *
 * Two nodes of the same service carry the same `serviceName`, and labelling
 * both from it produced two `module "ecs_service"` blocks -- a config that does
 * not even parse. A monorepo with six API services hits this immediately.
 */
function moduleNames(nodes: Node<ServiceNodeData>[]): Map<string, string> {
  const used = new Map<string, number>();
  const names = new Map<string, string>();

  for (const node of nodes) {
    const base = sanitizeName(node.data.serviceName) || sanitizeName(node.data.serviceId);
    const seen = used.get(base) ?? 0;
    used.set(base, seen + 1);
    names.set(node.id, seen === 0 ? base : `${base}_${seen + 1}`);
  }

  return names;
}

/**
 * Module inputs taken from the containers a node is drawn inside.
 *
 * The catalog says which argument each container contributes, so a service
 * added later inherits the wiring without anyone editing this file.
 */
function placementInputs(
  node: Node<ServiceNodeData>,
  nodes: Node<ServiceNodeData>[],
  names: Map<string, string>
): { variable: string; expression: string }[] {
  const placement = placementOf(node, nodes);
  const inputs: { variable: string; expression: string }[] = [];

  for (const link of parentLinks(node.data.serviceId)) {
    const containerId = placement[link.from];
    if (!containerId) continue;

    const containerName = names.get(containerId);
    if (!containerName) continue;

    inputs.push({ variable: snakeCase(link.argument), expression: `module.${containerName}.id` });
  }

  return inputs;
}

export function generateTerraformProject(
  nodes: Node<ServiceNodeData>[],
  _edges: Edge[]
): TerraformProject {
  const files: TerraformFile[] = [];

  if (nodes.length === 0) {
    files.push({
      path: 'main.tf',
      content: `# No resources to generate\n# Drag AWS services onto the canvas to create your architecture`,
    });
    return { files };
  }

  files.push({ path: 'main.tf', content: generateMainTf(nodes) });
  files.push({ path: 'variables.tf', content: generateVariablesTf() });
  files.push({ path: 'outputs.tf', content: generateOutputsTf(nodes) });

  const serviceTypes = new Set(nodes.map((n) => n.data.serviceId));
  serviceTypes.forEach((serviceId) => {
    const serviceNodes = nodes.filter((n) => n.data.serviceId === serviceId);
    const moduleFiles = generateServiceModule(serviceId, serviceNodes);
    files.push(...moduleFiles);
  });

  files.push({ path: 'README.md', content: generateReadme(nodes) });

  return { files };
}

export function generateTerraform(nodes: Node<ServiceNodeData>[], edges: Edge[]): string {
  const project = generateTerraformProject(nodes, edges);
  return project.files.map((f) => `# === ${f.path} ===\n${f.content}`).join('\n\n');
}

function generateMainTf(nodes: Node<ServiceNodeData>[]): string {
  let content = `# Generated by InfraCanvas
# Main Terraform Configuration

terraform {
  required_version = ">= 1.0"

  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }
  }
}

provider "aws" {
  region = var.aws_region

  default_tags {
    tags = {
      Environment = var.environment
      ManagedBy   = "Terraform"
      Project     = var.project_name
    }
  }
}

# Module Instances
`;

  const names = moduleNames(nodes);

  // Containers first, so the file reads outside-in and a reviewer meets the VPC
  // before the subnets that reference it.
  containersFirst(nodes).forEach((node) => {
    const name = names.get(node.id) as string;
    const placement = placementInputs(node, nodes, names)
      .map((input) => `  ${input.variable} = ${input.expression}`)
      .join('\n');

    content += `
module "${name}" {
  source = "./modules/${node.data.serviceId}"

  name        = "${name}"
  environment = var.environment
${generateModuleInputs(node)}${placement ? `\n${placement}` : ''}
}
`;
  });

  return content;
}

function generateModuleInputs(node: Node<ServiceNodeData>): string {
  const props = node.data.properties;
  const lines: string[] = [];

  Object.entries(props).forEach(([key, value]) => {
    if (value !== '' && value !== undefined && value !== null) {
      if (typeof value === 'string') {
        lines.push(`  ${key} = "${value}"`);
      } else if (typeof value === 'boolean') {
        lines.push(`  ${key} = ${value}`);
      } else if (typeof value === 'number') {
        lines.push(`  ${key} = ${value}`);
      }
    }
  });

  return lines.join('\n');
}

